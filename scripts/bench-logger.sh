#!/bin/bash
# Logger cost bench — MEASUREMENTS, not a gate. It decomposes one
# production-shaped logger call into its parts so an optimization can be
# ranked by measured share instead of by how visible the code looks.
#
# The driver (harness/fixture/bench/logger_cost.rb) runs each case on one
# thread and on several at once: a part that is cheap alone but serialized
# shows up in the multi-thread columns, which is the shape the request path
# has. Numbers are per call, median of the rounds.
#
# Usage: bash scripts/bench-logger.sh [--threads 1,8] [--rounds 5]
#        [--iterations 20000] [--output null|devnull]
#
# Exit: 0 when the bench ran (numbers on stdout), 1 on setup/build failure.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../cli/vendor-dir.sh
source "$ROOT/cli/vendor-dir.sh"

THREADS="1,8"
ROUNDS=5
ITERATIONS=20000
OUTPUT="null"
while (($#)); do
  case "$1" in
    --threads) THREADS="${2:?}"; shift 2 ;;
    --rounds) ROUNDS="${2:?}"; shift 2 ;;
    --iterations) ITERATIONS="${2:?}"; shift 2 ;;
    --output) OUTPUT="${2:?}"; shift 2 ;;
    *) echo "scripts/bench-logger.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done

# The pinned spinel decides the compile, as in every other harness run.
# shellcheck source=../cli/toolchain.sh
source "$ROOT/cli/toolchain.sh"
spinel_toolchain_ensure "$ROOT/pins.toml"
TOOLCHAIN_DIR="$(spinel_toolchain_dir "$ROOT/pins.toml")"
export PATH="$TOOLCHAIN_DIR:$PATH"

WORK="$ROOT/build/bench-logger"
mkdir -p "$WORK"

LOCK="$WORK.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  holder="$(cat "$LOCK/pid" 2>/dev/null || true)"
  if [[ -n $holder ]] && kill -0 "$holder" 2>/dev/null; then
    echo "[bench] another run (pid $holder) is using $WORK — retry when it finishes" >&2
    exit 1
  fi
  rm -rf "$LOCK"
  mkdir "$LOCK" 2>/dev/null || {
    echo "[bench] could not lock $WORK" >&2
    exit 1
  }
fi
printf '%s\n' "$$" > "$LOCK/pid"
trap 'rm -rf "$LOCK"' EXIT

find "$WORK" -mindepth 1 -maxdepth 1 ! -name build -exec rm -rf {} +
cp -a "$ROOT/harness/fixture/." "$WORK/"
cp -a "$ROOT/runtime" "$WORK/$SNAILS_VENDOR_DIR"

SEED="$ROOT/scaffold/seed/gen"
if [[ ! -f "$WORK/gen/.seed-stamp" ]] ||
  [[ -n "$(find "$SEED" -newer "$WORK/gen/.seed-stamp" -print -quit)" ]]; then
  rm -rf "$WORK/gen"
  cp -a "$SEED" "$WORK/gen"
  touch "$WORK/gen/.seed-stamp"
fi

cd "$WORK"
mkdir -p build
ENTRY="$WORK/build/logger_bench_entry.rb"
BINARY="$WORK/build/logger_bench"
printf '%s\n' '# generated by scripts/bench-logger.sh — do not edit' \
  'require_relative "../bench/logger_cost"' >"$ENTRY"

flags="$(spin flags | head -n 1)"
echo "[bench] compiling (pinned toolchain)" >&2
# shellcheck disable=SC2086
spinel "$ENTRY" $flags -O 1 -o "$BINARY" >&2

BENCH_THREADS="$THREADS" \
  BENCH_ROUNDS="$ROUNDS" \
  BENCH_ITERATIONS="$ITERATIONS" \
  BENCH_OUTPUT="$OUTPUT" \
  "$BINARY"
