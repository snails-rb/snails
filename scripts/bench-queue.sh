#!/bin/bash
# DB queue throughput bench — MEASUREMENTS, not a gate: it prints
# caller / worker-loop / direct-drain numbers and asserts nothing
# (timings vary per machine — record a run together with its date).
# Every job body is a no-op by default, so those are loop ceilings: a
# real job's duration bounds throughput separately. The driver lives in
# harness/fixture/bench/ (outside test/**, so the snapshot suite never
# picks it up) and this script compiles a one-off
# entry around it with the pinned toolchain.
#
# BENCH_LAUNCHER=1 runs the production path instead: the driver starts
# ActiveJob::Launcher with WORKER_CONCURRENCY=1/2/4/6/8, enqueues at
# BENCH_ARRIVAL_PER_MINUTE for BENCH_DURATION_SECONDS, and waits for the
# backlog to clear after arrivals stop.
#
# Workspace assembly mirrors scripts/test-runtime.sh (fixture app +
# core + queue template + gen seed) in its own directory, so a bench
# build never invalidates the gate's bundle cache.
#
# Usage: bash scripts/bench-queue.sh
#
# Env:
#   BENCH_LAUNCHER=1        run the Launcher/worker path sweep
#   BENCH_JOB_SLEEP_MS      body wait per job (default 0; 300 in launcher mode)
#   BENCH_ROWS              slow-profile row count (default 30)
#   BENCH_CONCURRENCY       direct-drain thread count in the spike (default 1)
#   BENCH_DURATION_SECONDS  launcher-mode arrival window (default 60)
#   BENCH_ARRIVAL_PER_MINUTE sustained arrivals in launcher mode (default 1000)
#   BENCH_VERBOSE=1         print a failure backtrace
#
# Exit: 0 when the bench ran (numbers on stdout), 1 on setup/build
# failure.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../cli/vendor-dir.sh
source "$ROOT/cli/vendor-dir.sh"

# The pinned spinel decides the compile — the same resolver the gates
# use (cli/toolchain.sh). The PATH's spin is never trusted.
# shellcheck source=toolchain.sh
source "$ROOT/cli/toolchain.sh"
spinel_toolchain_ensure "$ROOT/pins.toml"
TOOLCHAIN_DIR="$(spinel_toolchain_dir "$ROOT/pins.toml")"
export PATH="$TOOLCHAIN_DIR:$PATH"

WORK="$ROOT/build/bench-queue"
mkdir -p "$WORK"

# One run at a time: two runs sharing the build dir would race each
# other's compiles. A lock left by a dead run is taken over.
LOCK="$WORK.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  holder="$(cat "$LOCK/pid" 2>/dev/null || true)"
  if [[ -n $holder ]] && kill -0 "$holder" 2>/dev/null; then
    echo "[bench] another run (pid $holder) is using $WORK — retry when it finishes" >&2
    exit 1
  fi
  rm -rf "$LOCK"
  mkdir "$LOCK" 2>/dev/null || {
    echo "[bench] could not lock $WORK" >&2
    exit 1
  }
fi
printf '%s\n' "$$" > "$LOCK/pid"
trap 'rm -rf "$LOCK"' EXIT

find "$WORK" -mindepth 1 -maxdepth 1 ! -name build -exec rm -rf {} +
cp -a "$ROOT/harness/fixture/." "$WORK/"
cp -a "$ROOT/runtime" "$WORK/$SNAILS_VENDOR_DIR"
mkdir -p "$WORK/scaffold"
cp -a "$ROOT/scaffold/queue" "$WORK/scaffold/"

SEED="$ROOT/scaffold/seed/gen"
if [[ ! -f "$WORK/gen/.seed-stamp" ]] ||
  [[ -n "$(find "$SEED" -newer "$WORK/gen/.seed-stamp" -print -quit)" ]]; then
  rm -rf "$WORK/gen"
  cp -a "$SEED" "$WORK/gen"
  touch "$WORK/gen/.seed-stamp"
fi

cd "$WORK"
[[ $(command -v spin) == "$TOOLCHAIN_DIR/spin" ]] || {
  echo "[bench] spin did not resolve to the pinned toolchain: $TOOLCHAIN_DIR/spin" >&2
  exit 1
}

mkdir -p build
ENTRY="$WORK/build/queue_bench_entry.rb"
BINARY="$WORK/build/queue_bench"
printf '%s\n' '# generated by scripts/bench-queue.sh — do not edit' \
  'require_relative "../bench/queue_throughput"' >"$ENTRY"

flags="$(spin flags | head -n 1)"
echo "[bench] compiling (pinned toolchain)" >&2
# shellcheck disable=SC2086
spinel "$ENTRY" $flags -O 1 -o "$BINARY" >&2

if [[ ${BENCH_LAUNCHER:-0} == "1" ]]; then
  duration="${BENCH_DURATION_SECONDS:-60}"
  arrival="${BENCH_ARRIVAL_PER_MINUTE:-1000}"
  sleep_ms="${BENCH_JOB_SLEEP_MS:-300}"
  pool="${DATABASE_POOL_SIZE:-16}"
  echo "[bench] launcher sweep — ${arrival}/min for ${duration}s, ${sleep_ms}ms jobs, pool=${pool}, WORKER_CONCURRENCY=1/2/4/6/8" >&2
  for n in 1 2 4 6 8; do
    echo "[bench] WORKER_CONCURRENCY=$n" >&2
    WORKER_CONCURRENCY="$n" \
      DATABASE_POOL_SIZE="$pool" \
      "$BINARY"
  done
  exit 0
fi

echo "[bench] running — measurements only, nothing is asserted (sleep=${BENCH_JOB_SLEEP_MS:-0}ms, concurrency=${BENCH_CONCURRENCY:-1})" >&2
"$BINARY"
